export function resolverIcone(nome: string | null | undefined): LucideIcon {
  if (!nome) return Circle;
  const found = ICONES[nome];
  if (!found) {
    console.warn(`[iconesNavegacao] icone "${nome}" nao esta no mapa. Acrescente em src/config/iconesNavegacao.ts`);
    return Circle;
  }
  return found;
}

export const NOMES_ICONES = Object.keys(ICONES);

export function iconeConhecido(nome: string | null | undefined): boolean {
  return !!nome && Object.prototype.hasOwnProperty.call(ICONES, nome);
}
